declare(strict_types=1);

namespace PhpToBinary\Runtime;

class EngineRegistry
{
    private const SUPPORTED_TARGETS = [
        'linux-x86_64' => [
            'name'       => 'Linux x86_64 (musl static)',
            'os'         => 'linux',
            'arch'       => 'x86_64',
            'extension'  => '',
            'binary_tag' => 'php-8.3-micro-linux-x86_64',
        ],
        'linux-aarch64' => [
            'name'       => 'Linux aarch64 (ARM64 musl static)',
            'os'         => 'linux',
            'arch'       => 'aarch64',
            'extension'  => '',
            'binary_tag' => 'php-8.3-micro-linux-aarch64',
        ],
        'macos-arm64' => [
            'name'       => 'macOS arm64 (Apple Silicon)',
            'os'         => 'macos',
            'arch'       => 'arm64',
            'extension'  => '',
            'binary_tag' => 'php-8.3-micro-macos-arm64',
        ],
        'macos-x86_64' => [
            'name'       => 'macOS x86_64 (Intel Mac)',
            'os'         => 'macos',
            'arch'       => 'x86_64',
            'extension'  => '',
            'binary_tag' => 'php-8.3-micro-macos-x86_64',
        ],
        'windows-x64' => [
            'name'       => 'Windows x64 (.exe)',
            'os'         => 'windows',
            'arch'       => 'x64',
            'extension'  => '.exe',
            'binary_tag' => 'php-8.3-micro-windows-x64.exe',
        ],
    ];

    public static function getSupportedTargets(): array
    {
        return self::SUPPORTED_TARGETS;
    }

    public static function detectHostTarget(): string
    {
        $os = strtolower(PHP_OS);
        $arch = php_uname('m');

        if (str_starts_with($os, 'darwin')) {
            return ($arch === 'arm64' || $arch === 'aarch64') ? 'macos-arm64' : 'macos-x86_64';
        }

        if (str_starts_with($os, 'linux')) {
            return ($arch === 'aarch64' || $arch === 'arm64') ? 'linux-aarch64' : 'linux-x86_64';
        }

        if (str_starts_with($os, 'win')) {
            return 'windows-x64';
        }

        return 'linux-x86_64';
    }

    public static function getCacheDir(): string
    {
        $home = getenv('HOME') ?: (getenv('USERPROFILE') ?: sys_get_temp_dir());
        $dir = $home . '/.php-to-binary/engines';
        if (!is_dir($dir)) {
            @mkdir($dir, 0755, true);
        }
        return $dir;
    }

    /**
     * Generates a self-contained runtime wrapper stub for standalone execution
     */
    public static function generateStandaloneStub(string $pharName): string
    {
        return <<<STUB
#!/usr/bin/env php
<?php
/**
 * PHP-to-Binary Autonomous Standalone Execution Stub
 * Generated by PHP-to-Binary by Anton Barinov
 */
Phar::mapPhar('{$pharName}');
define('PHP_TO_BINARY_STANDALONE', true);
require 'phar://{$pharName}/entrypoint.php';
__HALT_COMPILER();
STUB;
    }
}
