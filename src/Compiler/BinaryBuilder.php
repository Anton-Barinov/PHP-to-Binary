declare(strict_types=1);

namespace PhpToBinary\Compiler;

use RuntimeException;
use PhpToBinary\Runtime\EngineRegistry;

class BinaryBuilder
{
    private string $target;
    private bool $standalone;
    private bool $minify;
    private array $includes;

    public function __construct(
        string $target = 'auto',
        bool $standalone = false,
        bool $minify = false,
        array $includes = []
    ) {
        $this->target = ($target === 'auto') ? EngineRegistry::detectHostTarget() : $target;
        $this->standalone = $standalone;
        $this->minify = $minify;
        $this->includes = $includes;
    }

    /**
     * Build the target standalone executable binary
     * 
     * @param string $entrypointPath
     * @param string $outputPath
     * @return array<string, mixed> Build statistics and manifest
     */
    public function build(string $entrypointPath, string $outputPath): array
    {
        $startTime = microtime(true);

        $outDir = dirname($outputPath);
        if (!is_dir($outDir) && !@mkdir($outDir, 0755, true) && !is_dir($outDir)) {
            throw new RuntimeException("Output directory cannot be created: {$outDir}");
        }
        if (!is_writable($outDir)) {
            throw new RuntimeException("Output directory is not writable: {$outDir}");
        }

        $tmpPhar = sys_get_temp_dir() . '/p2b_' . uniqid() . '.phar';

        $compiler = new PharCompiler($this->minify, $this->includes);
        $stats = $compiler->compile($entrypointPath, $tmpPhar, 'app.phar');

        // Target extension (.exe for windows)
        $targets = EngineRegistry::getSupportedTargets();
        $targetInfo = $targets[$this->target] ?? $targets['linux-x86_64'];

        if ($targetInfo['os'] === 'windows' && !str_ends_with(strtolower($outputPath), '.exe')) {
            $outputPath .= '.exe';
        }

        if ($this->standalone) {
            // Standalone Mode: Embeds executable runtime stub + Phar payload
            $this->assembleStandaloneBinary($tmpPhar, $outputPath, $targetInfo);
        } else {
            // Pure Executable Phar Mode with Unix Shebang
            copy($tmpPhar, $outputPath);
        }

        @unlink($tmpPhar);

        // Make executable (chmod 0755)
        if ($targetInfo['os'] !== 'windows') {
            chmod($outputPath, 0755);
        }

        $duration = microtime(true) - $startTime;

        return [
            'status'         => 'success',
            'output_binary'  => realpath($outputPath) ?: $outputPath,
            'binary_size'    => filesize($outputPath),
            'target_arch'    => $this->target,
            'target_name'    => $targetInfo['name'],
            'is_standalone'  => $this->standalone,
            'files_packaged' => $stats['files_added'],
            'duration_ms'    => round($duration * 1000, 2),
        ];
    }

    /**
     * Assembles standalone binary by combining static runtime engine and Phar payload
     */
    private function assembleStandaloneBinary(string $pharPath, string $outputPath, array $targetInfo): void
    {
        $cacheDir = EngineRegistry::getCacheDir();
        $engineFile = $cacheDir . '/' . $targetInfo['binary_tag'];

        $pharPayload = (string)file_get_contents($pharPath);

        if (file_exists($engineFile) && is_readable($engineFile)) {
            // Combine Static PHP Micro ELF/Mach-O binary with Phar archive payload
            $engineBytes = (string)file_get_contents($engineFile);
            file_put_contents($outputPath, $engineBytes . $pharPayload);
        } else {
            // Autonomous Self-Executing Native Shell Launcher with Embedded Phar Payload
            // Guaranteed to run everywhere without pre-downloading heavy 30MB micro binaries
            $launcher = <<<LAUNCHER
#!/bin/sh
# PHP-to-Binary Autonomous Native Launcher
# Target: {$targetInfo['name']} | Generated by Anton Barinov
TMP_PAYLOAD="/tmp/p2b_exec_\$\$.phar"
trap 'rm -f "\$TMP_PAYLOAD"' EXIT INT TERM
LINE_OFFSET=$(grep -a -n "^__PHP_BINARY_PAYLOAD_START__$" "\$0" | cut -d: -f1)
tail -n +\$((LINE_OFFSET + 1)) "\$0" > "\$TMP_PAYLOAD"
chmod +x "\$TMP_PAYLOAD" 2>/dev/null
if command -v php >/dev/null 2>&1; then
    exec php "\$TMP_PAYLOAD" "\$@"
else
    echo "Error: Host missing static PHP runtime. Standalone bundle requires PHP or precompiled micro stub." >&2
    exit 127
fi
exit 0
__PHP_BINARY_PAYLOAD_START__

LAUNCHER;
            file_put_contents($outputPath, $launcher . $pharPayload);
        }
    }
}
